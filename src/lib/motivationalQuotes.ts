const SHOWN_KEY = 'shown_quote_indices';

export function getRandomQuote(excludeIndices?: number[]): { quote: Quote; index: number } {
  const shown: number[] = excludeIndices || JSON.parse(localStorage.getItem(SHOWN_KEY) || '[]');
  
  const available = MOTIVATIONAL_QUOTES.map((_, i) => i).filter(i => !shown.includes(i));
  
  // If all shown, reset
  if (available.length === 0) {
    localStorage.setItem(SHOWN_KEY, '[]');
    const idx = Math.floor(Math.random() * MOTIVATIONAL_QUOTES.length);
    localStorage.setItem(SHOWN_KEY, JSON.stringify([idx]));
    return { quote: MOTIVATIONAL_QUOTES[idx], index: idx };
  }
  
  const idx = available[Math.floor(Math.random() * available.length)];
  const updated = [...shown, idx];
  localStorage.setItem(SHOWN_KEY, JSON.stringify(updated));
  return { quote: MOTIVATIONAL_QUOTES[idx], index: idx };
}
